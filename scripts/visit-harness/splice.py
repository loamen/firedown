#!/usr/bin/env python3
"""Splices the REAL visit-identity code out of GeckoState into one harness
class, so the checks run the shipped code and not a copy of it.

Lifted verbatim (modulo `private` -> package-private on the signature line,
and an optional mutation for teeth-checking): the NOISE_PARAMS,
POSITION_PARAMS and MAP_CAMERA_SEGMENT constants and updateVisit,
normalizedHost, pageKeyTail, withoutMapCamera, isQueryRefinement, refines,
withoutPosition, pathSegments, keyParams, pageIdentityKey and
originNamesPage. The fields updateVisit touches are declared here, and its
four collaborators (getTabId, pendingLoadSeq, setEntityTitle, setEntityIcon)
are stubs that count the resets so a check can see them.

usage: splice.py <repo-root> <out-dir>
           [--mutate=noposition|noguard|noimgindex|nomapcamera|noorigin]
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
out = Path(sys.argv[2])
mutate = next((a.split('=', 1)[1] for a in sys.argv[3:] if a.startswith('--mutate=')), None)

SRC = root / 'app/src/main/java/com/solarized/firedown/geckoview/GeckoState.java'
lines = SRC.read_text(encoding='utf-8').split('\n')


def extract_method(signature_re):
    """A method at 4-space indent: from its signature line to the first line
    that is exactly '    }'."""
    idx = [n for n, l in enumerate(lines) if re.match(signature_re, l)]
    if len(idx) != 1:
        raise SystemExit(f'expected one match for {signature_re!r}, got {len(idx)}')
    i = idx[0]
    j = i
    while lines[j] != '    }':
        j += 1
    body = lines[i:j + 1]
    body[0] = re.sub(r'^(\s+)private ', r'\1', body[0])
    return '\n'.join(body)


def extract_constant(name):
    idx = [n for n, l in enumerate(lines)
           if re.match(rf'\s+(public |private )?static final [\w<>, ]+ {name} = ', l)]
    if len(idx) != 1:
        raise SystemExit(f'expected one constant {name}, got {len(idx)}')
    i = idx[0]
    j = i
    while not lines[j].rstrip().endswith(';'):
        j += 1
    body = lines[i:j + 1]
    body[0] = re.sub(r'^(\s+)private ', r'\1', body[0])
    return '\n'.join(body)


constants = '\n'.join(extract_constant(c)
                      for c in ['NOISE_PARAMS', 'POSITION_PARAMS', 'MAP_CAMERA_SEGMENT'])
methods = '\n\n'.join(extract_method(r) for r in [
    r'\s+private boolean updateVisit\(String uri\)',
    r'\s+private static String normalizedHost\(String',
    r'\s+private static String pageKeyTail\(String',
    r'\s+private static String withoutMapCamera\(String',
    r'\s+static boolean isQueryRefinement\(String',
    r'\s+private static boolean refines\(String',
    r'\s+private static Map<String, String> withoutPosition\(',
    r'\s+private static int pathSegments\(String',
    r'\s+private static Map<String, String> keyParams\(String',
    r'\s+private static String pageIdentityKey\(String',
    r'\s+public static boolean originNamesPage\(',
])

def mutate_text(text, old, new, label):
    if old not in text:
        raise SystemExit(f'mutation {label} did not apply')
    return text.replace(old, new)


if mutate == 'noposition':
    constants = mutate_text(constants, 'Arrays.asList("index", "img_index")',
                            'Collections.<String>emptyList()', mutate)
elif mutate == 'noimgindex':
    constants = mutate_text(constants, 'Arrays.asList("index", "img_index")',
                            'Arrays.asList("index")', mutate)
elif mutate == 'noguard':
    methods = mutate_text(
        methods,
        '        if ((ia.isEmpty() || ib.isEmpty()) && pathSegments(baseA) < 2) return false;\n',
        '', mutate)
elif mutate == 'nomapcamera':
    methods = mutate_text(methods,
                          'if (!MAP_CAMERA_SEGMENT.matcher(seg).matches()) kept.add(seg);',
                          'kept.add(seg);', mutate)
elif mutate == 'noorigin':
    methods = mutate_text(methods,
                          'return key.equals(pageKey) || isQueryRefinement(key, pageKey);',
                          'return false;', mutate)
elif mutate is not None:
    raise SystemExit(f'unknown mutation {mutate}')

java = f'''package com.solarized.firedown.geckoview;

import android.net.Uri;

import com.solarized.firedown.utils.DebugLog;

import androidx.annotation.Nullable;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.regex.Pattern;

/** GENERATED by scripts/visit-harness/splice.py from GeckoState.java. */
public class VisitModel {{
{constants}

    private final Map<String, Integer> mVisitIdByKey = new HashMap<>();
    public int mVisitId;
    int mMaxVisitId;
    String mCurrentPageKey;
    String mCurrentPageHost;
    public int titleResets;
    public int iconResets;

    int getTabId() {{ return 1; }}
    int pendingLoadSeq() {{ return 0; }}
    void setEntityTitle(String title) {{ titleResets++; }}
    void setEntityIcon(String icon) {{ iconResets++; }}

    /** The harness's door to the spliced private method. */
    public boolean locationChange(String uri) {{ return updateVisit(uri); }}

    public static boolean refinement(String a, String b) {{ return isQueryRefinement(a, b); }}

    public static String key(String uri) {{ return pageIdentityKey(uri); }}

    public static boolean belongs(String origin, String pageUrl) {{
        return originNamesPage(origin, pageIdentityKey(pageUrl));
    }}

{methods}
}}
'''
dest = out / 'com/solarized/firedown/geckoview'
dest.mkdir(parents=True, exist_ok=True)
(dest / 'VisitModel.java').write_text(java, encoding='utf-8')
